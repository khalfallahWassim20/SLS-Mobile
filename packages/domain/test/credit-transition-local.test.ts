import {test} from 'node:test';
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {createHash,randomUUID} from 'node:crypto';
import {canonicalJson} from '@sls/domain';
import {assertTransitionLocalHistory} from '../../../apps/mobile/credit-transition-local.js';

test('transition avoir : chaque opération locale doit avoir une preuve serveur correspondante',async()=>{
 const db=new DatabaseSync(':memory:');try{
  db.exec(`CREATE TABLE sales(id INTEGER PRIMARY KEY,client_id TEXT,payload TEXT);
  CREATE TABLE settlements(id INTEGER PRIMARY KEY,client_id TEXT,payload TEXT);
  CREATE TABLE tour_pre_invoices(id TEXT PRIMARY KEY,client_id TEXT,journal_date TEXT,payload TEXT);
  CREATE TABLE tour_journal_receipts(id TEXT PRIMARY KEY,pre_invoice_id TEXT,client_id TEXT,journal_date TEXT,payload TEXT);
  CREATE TABLE journal_sync_state(invoice_id TEXT PRIMARY KEY,version INTEGER,payload TEXT);`);
  const tx={getAllAsync:async<T>(sql:string,...params:(string|number|null)[])=>db.prepare(sql).all(...params) as T[]};
  const digest=async(text:string)=>createHash('sha256').update(text).digest('hex');
  const client=randomUUID(),saleId=randomUUID(),paymentId=randomUUID(),journalId=randomUUID();
  const sale={clientId:client,syncSaleId:saleId,syncVersion:1,total:1000,paid:100,name:'original'};
  const payment={clientId:client,syncOperationId:paymentId,amount:100};
  const journal={version:1,invoice:{id:journalId,clientId:client,journalDate:'2026-11-08',amount:200},receipts:[]};
  db.prepare('INSERT INTO sales VALUES(1,?,?)').run(client,JSON.stringify(sale));
  db.prepare('INSERT INTO settlements VALUES(1,?,?)').run(client,JSON.stringify(payment));
  db.prepare('INSERT INTO tour_pre_invoices VALUES(?,?,?,?)').run(journalId,client,journal.invoice.journalDate,JSON.stringify(journal.invoice));
  db.prepare('INSERT INTO journal_sync_state VALUES(?,?,?)').run(journalId,1,JSON.stringify(journal));
  const ref:any={saleStates:[{saleId,clientId:client,version:1,total:'1000',paid:'100',creditNote:null}],eligibleSaleProofs:[{saleId,version:1,hash:await digest(canonicalJson(sale))}],settlementStates:[{operationId:paymentId,clientId:client}],settlementProofs:[{operationId:paymentId,hash:await digest(canonicalJson(payment))}],journalStates:[{id:journalId,clientId:client,creditNote:null}],journalProofs:[{id:journalId,version:1,hash:await digest(canonicalJson(journal))}]};
  await assertTransitionLocalHistory(tx,ref,digest);
  await assert.rejects(assertTransitionLocalHistory(tx,{...ref,saleStates:[]},digest),/Vente locale/);
  db.prepare('UPDATE sales SET payload=?').run(JSON.stringify({...sale,name:'modifié'}));
  await assert.rejects(assertTransitionLocalHistory(tx,ref,digest),/Vente locale/);
  db.prepare('UPDATE sales SET payload=?').run(JSON.stringify(sale));
  await assert.rejects(assertTransitionLocalHistory(tx,{...ref,settlementStates:[]},digest),/Règlement local/);
  await assert.rejects(assertTransitionLocalHistory(tx,{...ref,settlementProofs:null},digest),/Règlement local/);
  db.prepare('UPDATE settlements SET payload=?').run(JSON.stringify({...payment,amount:200}));
  await assert.rejects(assertTransitionLocalHistory(tx,ref,digest),/Règlement local/);
  db.prepare('UPDATE settlements SET payload=?').run(JSON.stringify(payment));
  db.prepare('UPDATE tour_pre_invoices SET payload=?').run(JSON.stringify({...journal.invoice,amount:300}));
  await assert.rejects(assertTransitionLocalHistory(tx,ref,digest),/Préétablie locale/);
  db.prepare('UPDATE tour_pre_invoices SET payload=?').run(JSON.stringify(journal.invoice));
  const receiptId=randomUUID(),receipt={id:receiptId,preInvoiceId:journalId,clientId:client,journalDate:journal.invoice.journalDate};
  db.prepare('INSERT INTO tour_journal_receipts VALUES(?,?,?,?,?)').run(receiptId,journalId,client,journal.invoice.journalDate,JSON.stringify(receipt));
  await assert.rejects(assertTransitionLocalHistory(tx,ref,digest),/Préétablie locale/);
  const paidJournal={...journal,version:2,receipts:[receipt]};
  db.prepare('UPDATE journal_sync_state SET version=2,payload=?').run(JSON.stringify(paidJournal));
  const paidRef={...ref,journalProofs:[{id:journalId,version:2,hash:await digest(canonicalJson(paidJournal))}]};
  await assertTransitionLocalHistory(tx,paidRef,digest);
  db.prepare('UPDATE tour_journal_receipts SET client_id=?').run(randomUUID());
  await assert.rejects(assertTransitionLocalHistory(tx,paidRef,digest),/Préétablie locale/);
  db.prepare('UPDATE journal_sync_state SET version=1,payload=?').run(JSON.stringify(journal));
  db.prepare('DELETE FROM tour_journal_receipts').run();
  db.prepare('INSERT INTO tour_journal_receipts VALUES(?,?,?,?,?)').run(receiptId,randomUUID(),client,journal.invoice.journalDate,JSON.stringify(receipt));
  await assert.rejects(assertTransitionLocalHistory(tx,ref,digest),/Journal local orphelin/);
  db.prepare('DELETE FROM tour_journal_receipts').run();
  db.prepare('INSERT INTO journal_sync_state VALUES(?,?,?)').run(randomUUID(),1,'{}');
  await assert.rejects(assertTransitionLocalHistory(tx,ref,digest),/Journal local orphelin/);
  db.prepare('DELETE FROM journal_sync_state WHERE invoice_id<>?').run(journalId);
  db.prepare('UPDATE journal_sync_state SET payload=?').run(JSON.stringify({...journal,receipts:[{id:randomUUID()}]}));
  await assert.rejects(assertTransitionLocalHistory(tx,ref,digest),/Préétablie locale/);
  assert.equal(db.prepare('SELECT count(*) AS n FROM sales').get()?.n,1);
  assert.equal(db.prepare('SELECT count(*) AS n FROM settlements').get()?.n,1);
  assert.equal(db.prepare('SELECT count(*) AS n FROM tour_pre_invoices').get()?.n,1);
 }finally{db.close();}
});
